def area(a, h):
    #Takes two numbers, returns one number
    #Specified for calculating triangle's area using the "S = a * h / 2" formula
    return a * h / 2

def perimetr(a, b, c):
    #Takes three numbers, returns one number
    #Specified for calculating triangle's perimetr
    return a + b + c

def SideEqualityCheck(a, b, c):
    #Takes three numbers, return one bool
    #Specified for checking are sides equal to each other
    return a == b == c

