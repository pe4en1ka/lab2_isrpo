def area(a, h):
    #Takes two numbers, returns one number
    #Specified for calculating triangles area using the "S = a * h / 2" formula
    return a * h / 2

def perimetr(a, b, c):
    #Takes three numbers, returns one number
    #Specified for calculating triangles perimetr
    return a + b + c

def SideEqualityCheck(a, b, c):
    return a == b == c

